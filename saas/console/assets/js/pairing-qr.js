/* One-time tenant pairing QR. Runs entirely in the authenticated browser.
 * No external QR service, tracking, or network request receives the secret. */
(function () {
  "use strict";
  const mount = (scope=document) => {
  const panels = scope.querySelectorAll("[data-pair-code][data-pair-slot]");
  for (const panel of panels) {
    const code = panel.getAttribute("data-pair-code") || "";
    const slot = panel.getAttribute("data-pair-slot");
    if (!/^[A-Fa-f0-9]{4}(?:-?[A-Fa-f0-9]{4}){5}$/.test(code) || !/^[01]$/.test(slot) || code[0] !== slot) {
      panel.textContent = "رمز QR غير صالح";
      continue;
    }
    const uri = "ontrackvoice://pair?slot=" + slot + "&code=" + code;
    try {
      if (typeof qrcode !== "function") throw new Error("QR library unavailable");
      const qr = qrcode(0, "M");
      qr.addData(uri);
      qr.make();
      // SVG bytes are generated by the local, bundled MIT library.
      panel.innerHTML = qr.createSvgTag({cellSize: 4, margin: 8, scalable: true,
        alt: "رمز اقتران SIM " + (Number(slot) + 1)});
      const button = document.querySelector('[data-pair-copy="' + slot + '"]');
      if (button) button.addEventListener("click", async () => {
        try {
          await navigator.clipboard.writeText(uri);
          button.textContent = "تم النسخ";
        } catch (_) {
          const field = document.createElement("input");
          field.type = "text"; field.readOnly = true; field.value = uri; field.dir = "ltr";
          field.setAttribute("aria-label", "رابط الربط للنسخ اليدوي");
          panel.parentNode?.appendChild(field);
          field.focus(); field.select();
          try { if (document.execCommand("copy")) { button.textContent = "تم النسخ"; return; } } catch (_) {}
          button.textContent = "الرابط محدد — انسخه من قائمة النص";
        }
      });
    } catch (_) {
      panel.textContent = "تعذر إنشاء QR؛ أدخل الرمز يدويًا في Android";
    }
  }
  };
  window.ontrackMountPairingQR=mount;
  mount();
}());
